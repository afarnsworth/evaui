// Builds the installable web app in tracker/ from the tracker fragment (the
// form the artifact host expects): index.html, manifest.webmanifest and a
// versioned service worker. Icons come from scripts/make-icons.mjs.
import {createHash} from 'node:crypto';
import {readFileSync, readdirSync, writeFileSync} from 'node:fs';

const DIR = 'tracker';
const BG = '#030504';

const body = readFileSync(`${DIR}/life-tracker.html`, 'utf8');

const manifest = {
  name: 'NERV Life Support',
  short_name: 'Life Support',
  description: 'Two-player Magic: The Gathering life tracker styled as a NERV battery display.',
  id: './',
  start_url: './',
  scope: './',
  display: 'fullscreen',
  display_override: ['fullscreen', 'standalone'],
  orientation: 'portrait',
  background_color: BG,
  theme_color: BG,
  icons: [
    {src: 'icons/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any'},
    {src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any'},
    {src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable'},
  ],
};

const page = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="theme-color" content="${BG}">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
<meta name="apple-mobile-web-app-title" content="${manifest.short_name}">
<link rel="manifest" href="manifest.webmanifest">
<link rel="icon" type="image/png" sizes="32x32" href="icons/favicon-32.png">
<link rel="apple-touch-icon" href="icons/apple-touch-icon.png">
<style>:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}body{margin:0}</style>
${body.trim()}
<script>
if ('serviceWorker' in navigator) {
  addEventListener('load', () => navigator.serviceWorker.register('sw.js').catch(() => {}));
}
</script>
</html>
`;

const icons = readdirSync(`${DIR}/icons`).filter((f) => f.endsWith('.png')).sort();
const shell = ['./', 'index.html', 'manifest.webmanifest', ...icons.map((f) => `icons/${f}`)];

// The cache name changes whenever any shipped file changes, so an update
// replaces the old cache instead of serving stale files forever.
const hash = createHash('sha256');
hash.update(page);
hash.update(JSON.stringify(manifest));
for (const f of icons) hash.update(readFileSync(`${DIR}/icons/${f}`));
const version = hash.digest('hex').slice(0, 12);

const sw = `// Generated by scripts/build-tracker.mjs. Do not edit by hand.
const SHELL_CACHE = 'life-support-${version}';
const FONT_CACHE = 'life-support-fonts';
const SHELL = ${JSON.stringify(shell)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(SHELL_CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== SHELL_CACHE && k !== FONT_CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);

  // The page itself: network first so updates arrive, cache when offline.
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(SHELL_CACHE).then((c) => c.put('index.html', copy));
          return res;
        })
        .catch(() => caches.match('index.html')),
    );
    return;
  }

  // Google Fonts: cache first, so the typefaces work offline after one visit.
  if (url.hostname === 'fonts.googleapis.com' || url.hostname === 'fonts.gstatic.com') {
    event.respondWith(
      caches.open(FONT_CACHE).then((c) =>
        c.match(req).then((hit) => hit || fetch(req).then((res) => (c.put(req, res.clone()), res))),
      ),
    );
    return;
  }

  // Everything else from this site: cache first.
  if (url.origin === self.location.origin) {
    event.respondWith(caches.match(req).then((hit) => hit || fetch(req)));
  }
});
`;

writeFileSync(`${DIR}/index.html`, page);
writeFileSync(`${DIR}/manifest.webmanifest`, JSON.stringify(manifest, null, 2) + '\n');
writeFileSync(`${DIR}/sw.js`, sw);
console.log(`built ${DIR}/ (cache ${version})`);
